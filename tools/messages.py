def build(i):
    out = {}
    for k, v in M.items():
        s = v[i]
        ph = {}
        def sub(m):
            ph['n' + m.group(1)] = {'content': '$' + m.group(1)}
            return '$N' + m.group(1) + '$'
        s = re.sub(r'\$(\d)', sub, s)
        e = {'message': s}
        if ph: e['placeholders'] = ph
        out[k] = e
    return out
for i, loc in enumerate(('es', 'en')):
    p = pathlib.Path(__file__).resolve().parent.parent / '_locales' / loc / 'messages.json'
    p.write_text(json.dumps(build(i), ensure_ascii=False, indent=2) + '\n')
